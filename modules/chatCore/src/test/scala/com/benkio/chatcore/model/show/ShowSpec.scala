package com.benkio.chatcore.model.show

import cats.implicits.*
import com.benkio.chatcore.conversions.YouTubeTimestamp.finiteDurationToYoutubeTimestamp
import com.benkio.chatcore.model.SBotInfo.SBotId
import com.benkio.chatcore.Arbitraries.given
import munit.ScalaCheckSuite
import org.scalacheck.Gen
import org.scalacheck.Prop.forAll

import java.time.LocalDate
import scala.concurrent.duration.*

class ShowSpec extends ScalaCheckSuite {

  property("show instance should render youtube url without timestamp when missing") {
    forAll { (show: Show) =>
      val baseShow = show.copy(timestamp = None)
      val expected =
        s"""${baseShow.uploadDate} - https://www.youtube.com/watch?v=${baseShow.id}
           | ${baseShow.title}
           |----------
           | ${baseShow.description.getOrElse("")}""".stripMargin
      assertEquals(baseShow.show, expected)
    }
  }

  property("show instance should render youtube url with timestamp query when present") {
    forAll { (show: Show) =>
      val showWithTimestamp = show.copy(timestamp = Some(1.hour + 2.minutes + 3.seconds))
      val expected          =
        s"""${show.uploadDate} - https://www.youtube.com/watch?v=${show.id}&t=1h2m3s
           | ${show.title}
           |----------
           | ${show.description.getOrElse("")}""".stripMargin
      assertEquals(showWithTimestamp.show, expected)
    }
  }

  property("show instance should include fields generated by Arbitrary[Show]") {
    forAll { (show: Show) =>
      val rendered = show.show
      assert(rendered.contains(show.uploadDate.toString))
      assert(rendered.contains(s"https://www.youtube.com/watch?v=${show.id}"))
      assert(rendered.contains(show.title))
      assert(rendered.contains(show.description.getOrElse("")))
      show.timestamp match {
        case Some(timestamp) =>
          assert(rendered.contains(s"&t=${finiteDurationToYoutubeTimestamp(timestamp)}"))
        case None =>
          assert(!rendered.contains("&t="))
      }
    }
  }

  property("addTimestamp(ShowQuery) should set timestamp from matching captions") {
    val keywordGen = Gen.alphaLowerStr.suchThat(_.length >= 4)
    val tsGen      = Gen.choose(1L, 10_000L)
    forAll(keywordGen, tsGen) { (keyword: String, timestampSeconds: Long) =>
      val timestamp = timestampSeconds.seconds
      if keyword.trim.nonEmpty && timestampSeconds > 0 then {
        val original = Show(
          id = "abc123",
          botId = SBotId("botid"),
          title = "title",
          uploadDate = LocalDate.of(2020, 1, 1),
          duration = 120,
          description = None,
          isLive = false,
          originAutomaticCaption = None,
          originAutomaticCaptionSrt = Vector(
            2.seconds -> "1234567890",
            timestamp -> s"caption contains $keyword"
          ),
          timestamp = None
        )

        val query = ShowQueryKeyword(titleKeywords = None, captionKeywords = Some(List(keyword)))
        assertEquals(original.addTimestamp(query).timestamp, Some(timestamp))
      } else assert(true)
    }
  }

  property("addTimestamp(String) should parse valid youtube timestamp and ignore invalid ones") {
    forAll(Gen.alphaStr.suchThat(_.nonEmpty).map(_ + "_invalid")) { (invalidTimestamp: String) =>
      val original = Show(
        id = "abc123",
        botId = SBotId("botid"),
        title = "title",
        uploadDate = LocalDate.of(2020, 1, 1),
        duration = 120,
        description = None,
        isLive = false,
        originAutomaticCaption = None,
        originAutomaticCaptionSrt = Vector.empty,
        timestamp = None
      )

      assertEquals(original.addTimestamp("1h2m3s").timestamp, Some(3723.seconds))
      assertEquals(original.addTimestamp(invalidTimestamp).timestamp, None)
    }
  }
}
